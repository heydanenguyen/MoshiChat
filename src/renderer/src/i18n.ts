const dictionaries: Record<Language, Dictionary> = { vi, en }

export function translate(lang: Language, key: TKey, params?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) text = text.replace(`{${k}}`, String(v))
  return text
}
